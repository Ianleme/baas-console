import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

import { NestFactory } from '@nestjs/core';
import openapiTS, { astToString } from 'openapi-typescript';
import { format } from 'prettier';

const repositoryRoot = fileURLToPath(new URL('..', import.meta.url));
export const defaultGeneratedPath = resolve(
  repositoryRoot,
  'packages/api-client/src/generated/schema.ts'
);

export class GeneratedClientDriftError extends Error {
  constructor() {
    super('API_CLIENT_DRIFT_DETECTED');
    this.name = 'GeneratedClientDriftError';
  }
}

function sortRecursively(value) {
  if (Array.isArray(value)) return value.map(sortRecursively);
  if (!value || typeof value !== 'object') return value;
  return Object.fromEntries(
    Object.entries(value)
      .sort(([left], [right]) => left.localeCompare(right))
      .map(([key, nested]) => [key, sortRecursively(nested)])
  );
}

export async function loadOpenApiDocument() {
  const [{ AppModule }, { createOpenApiDocument }] = await Promise.all([
    import('../apps/api/dist/app.module.js'),
    import('../apps/api/dist/platform/configure-application.js')
  ]);
  const app = await NestFactory.create(AppModule, { logger: false });
  try {
    await app.init();
    return sortRecursively(createOpenApiDocument(app));
  } finally {
    await app.close();
  }
}

export async function generateClientSource(document) {
  const nodes = await openapiTS(sortRecursively(document), {
    alphabetize: true,
    exportType: true
  });
  return format(
    [
      '// Generated by scripts/generate-api-client.mjs. Do not edit manually.',
      '// Source: BaaS Console NestJS OpenAPI document.',
      '',
      astToString(nodes).trimEnd(),
      ''
    ].join('\n'),
    { parser: 'typescript', singleQuote: true, trailingComma: 'none' }
  );
}

export async function checkGeneratedClient(path = defaultGeneratedPath, document) {
  if (!existsSync(path)) throw new GeneratedClientDriftError();
  const expected = await generateClientSource(document ?? (await loadOpenApiDocument()));
  if (readFileSync(path, 'utf8') !== expected) throw new GeneratedClientDriftError();
  return { status: 'current' };
}

export async function writeGeneratedClient(path = defaultGeneratedPath) {
  const source = await generateClientSource(await loadOpenApiDocument());
  mkdirSync(dirname(path), { recursive: true });
  writeFileSync(path, source, 'utf8');
  return path;
}

const invokedAsScript = process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1];
if (invokedAsScript) {
  try {
    if (process.argv.includes('--check')) {
      await checkGeneratedClient();
      process.stdout.write('API_CLIENT_CURRENT\n');
    } else {
      const output = await writeGeneratedClient();
      process.stdout.write(`API_CLIENT_GENERATED ${output}\n`);
    }
  } catch (error) {
    process.stderr.write(`${error instanceof Error ? error.message : String(error)}\n`);
    process.exitCode = 1;
  }
}
